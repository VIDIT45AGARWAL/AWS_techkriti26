#!/usr/bin/env node
/**
 * deploy.js — Cross-platform deploy script for CivicAlert frontend.
 *
 * Usage:  node deploy.js
 *
 * Steps:
 *   1. Reads the backend EC2 IP from Terraform output
 *   2. Writes a .env.local with NEXT_PUBLIC_API_URL pointing to the EC2 backend
 *   3. Builds the Next.js static export (npm run build)
 *   4. Syncs the `out/` folder to S3
 *   5. Invalidates the CloudFront cache
 */

const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const tfDir = path.join(__dirname, "terraform");
const envLocalPath = path.join(__dirname, ".env.local");

function run(cmd, opts = {}) {
  console.log(`\n▶ ${cmd}`);
  execSync(cmd, { stdio: "inherit", ...opts });
}

function tfOutput(name) {
  return execSync(`terraform output -raw ${name}`, {
    cwd: tfDir,
    encoding: "utf-8",
  }).trim();
}

// 1. Read frontend CloudFront domain from Terraform
let cfDomain;
try {
  cfDomain = tfOutput("frontend_cloudfront_domain");
} catch {
  console.error("❌ Could not read frontend_cloudfront_domain from terraform output.");
  console.error("   Make sure you have run 'terraform apply' in the terraform/ directory first.");
  process.exit(1);
}

const apiUrl = `https://${cfDomain}`;
console.log(`\n🔗 Backend API URL (Proxied): ${apiUrl}`);

// 2. Write .env.local so Next.js bakes the correct API URL at build time
const envContent = `# Auto-generated by deploy.js — do not edit manually\nNEXT_PUBLIC_API_URL=${apiUrl}\n`;
fs.writeFileSync(envLocalPath, envContent, "utf-8");
console.log(`📝 Wrote ${envLocalPath}`);

// 3. Build
run("npm run build");

// 4. Get S3 bucket and CloudFront distribution ID
const bucket = tfOutput("frontend_s3_bucket");
const distId = tfOutput("cloudfront_distribution_id");

console.log(`\n📦 Deploying to s3://${bucket}`);
console.log(`🌐 CloudFront Distribution: ${distId}`);

// 5. Sync to S3
run(`aws s3 sync out/ s3://${bucket} --delete`);

// 6. Invalidate CloudFront
run(`aws cloudfront create-invalidation --distribution-id ${distId} --paths "/*"`);

console.log("\n✅ Deploy complete! Your site will be live in ~60 seconds.");
console.log(`   Frontend: https://${tfOutput("frontend_cloudfront_domain")}`);
console.log(`   Backend:  ${apiUrl}`);
